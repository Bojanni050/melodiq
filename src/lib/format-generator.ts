/**
 * Human-readable label for what generated a track.
 *
 * The database stores the internal pair (`provider` + `provider_model`), which
 * is not what anyone recognises. "poyo" + "V5_5" is a Suno 5.5 track — PoYo is
 * the API that fronts Suno in this app, not a generator in its own right — and
 * the model column holds internal identifiers like "V5_5" or
 * "minimax-music-2.6" rather than product names. Showing the raw columns would
 * be technically accurate and practically useless.
 *
 * Lives in lib/ rather than in the component because more than one surface
 * shows this, and a duplicated mapping is a duplicated thing to forget when a
 * provider is added.
 */

