/**
 * Providers that ARE the product they serve, so their prefix would only stutter
 * ("Lyria Lyria 3") or misattribute a passthrough ("Suno MiniMax 2.6"). The
 * model label is then used verbatim.
 */
const SELF_PROVIDERS = new Set([
  "poyo", "suno", "lyria", "mureka", "minimax", "musicgpt", "heartmula", "tempolor",
]);

/**
 * Gateway providers (APIMart, APIFrame) sell other people's models. For a model
 * that names a real product, the label stands alone — "APIMart Suno 5.5" would
 * make the track indistinguishable from a native one. For a model that does not
 * (a bare MiniMax build), the prefix is the only provenance left.
 */
const STANDALONE_MODEL: Record<string, Set<string>> = {
  "apimart/lyria3": new Set(["lyria3"]),
  "apimart/suno5": new Set(["suno5"]),
  "apimart/suno55": new Set(["suno55"]),
  "apimart/minimaxmusic26": new Set(["minimaxmusic26"]),
  "apiframe/lyria3": new Set(["lyria3"]),
  "apiframe/minimaxmusic26": new Set(["minimaxmusic26"]),
};

function normalizeModelKey(model: string): string {
  return model.toLowerCase().replace(/[^a-z0-9]/g, "");
}

/**
 * Returns e.g. "Suno 5.5", "Lyria 3", "Mureka" (model unknown) or null when
 * neither column holds anything worth showing.
 *
 * Null rather than a placeholder: an uploaded track with no providerModel
 * still reports "Uploaded" from the provider alone, but a track where both are
 * empty shows nothing instead of an empty bullet. An unrecognised model falls
 * back to the raw string rather than being dropped — a wrong-but-present label
 * beats silently missing provenance.
 */
export function formatGenerator(
  provider: string | null | undefined,
  model?: string | null
): string | null {
  const providerKey = (provider ?? "").trim().toLowerCase();
  const rawModel = (model ?? "").trim();

  if (!providerKey && !rawModel) return null;

  const modelKey = normalizeModelKey(rawModel);
  const modelMap = MODEL_LABEL[providerKey];
  const modelLabel = modelKey && modelMap ? modelMap[modelKey] : undefined;

  // A model that is already a friendly name (older rows, or a provider we have
  // no entry for) is shown as-is rather than replaced by the provider name.
  if (!modelLabel && rawModel) {
    return /[a-z]/i.test(rawModel) && !modelKey ? rawModel : PROVIDER_LABEL[providerKey] ?? rawModel;
  }

  const providerLabel = PROVIDER_LABEL[providerKey];
  if (modelLabel && providerLabel) {
    const standAlone =
      SELF_PROVIDERS.has(providerKey) || STANDALONE_MODEL[`${providerKey}/${modelKey}`]?.has(modelKey);
    return standAlone ? modelLabel : `${providerLabel} ${modelLabel}`;
  }
  return modelLabel ?? providerLabel ?? rawModel ?? null;
}
